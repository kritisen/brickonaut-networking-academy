  // registerLevel(level, questions): adds a new world (e.g. a bonus level).
  // level: { id (number, unique), key, name, body, subtitle, art, accent, bonus?, map?, briefing?, twist?, outro? }
  // questions: same schema as above; `level` is filled in automatically.
  ONA.registerLevel = function (level, questions) {
    if (!level || typeof level.id !== 'number') throw new Error('registerLevel: level.id (number) required');
    if (ONA.LEVELS.some(function (l) { return l.id === level.id; })) throw new Error('registerLevel: duplicate level id ' + level.id);
    level.shields = level.shields || 3;
    level.briefing = level.briefing || [{ who: 'vega', text: 'Incoming transmission, Cadet. Decode it.' }];
    level.twist = level.twist || [];
    level.outro = level.outro || [{ who: 'vega', text: 'Transmission decoded. Good work.' }];
    ONA.LEVELS.push(level);
    (questions || []).forEach(function (q) { q.level = level.id; ONA.QUESTIONS.push(q); });
    return level;
  };
